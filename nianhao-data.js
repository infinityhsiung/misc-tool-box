'use strict';

const eraData = [];
function addGroup(dynasty, ruler, records, source = '') {
  records.split(';').forEach(record => {
    const [era, start, end] = record.split('|');
    eraData.push({ dynasty, ruler, era, start: Number(start), end: Number(end), eraStart: Number(start), eraEnd: Number(end), source });
  });
}
function addRecord(dynasty, ruler, era, start, end, source = '', eraStart = start, eraEnd = end) {
  eraData.push({ dynasty, ruler, era, start, end, eraStart, eraEnd, source, noEra: !era });
}

