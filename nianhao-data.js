function smallChinese(value) {
  const digits = '零一二三四五六七八九';
  const units = ['千', '百', '十', ''];
  const powers = [1000, 100, 10, 1];
  let text = '';
  let zero = false;
  powers.forEach((power, index) => {
    const digit = Math.floor(value / power) % 10;
    if (!digit) { if (text && value % power) zero = true; return; }
    if (zero) { text += '零'; zero = false; }
    text += power === 10 && digit === 1 && !text ? units[index] : digits[digit] + units[index];
  });
  return text || '零';
}
